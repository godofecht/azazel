#!/usr/bin/env python3
"""Write build_info.zig from the package version in build.zig.zon.

usage: build_info.py <build.zig.zon> <output.zig>
"""

import re
import sys


def main() -> int:
    zon_path, out_path = sys.argv[1], sys.argv[2]
    with open(zon_path, encoding="utf-8") as handle:
        match = re.search(r'\.version\s*=\s*"([^"]+)"', handle.read())
    if not match:
        print(f"{zon_path}: no .version field", file=sys.stderr)
        return 1
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("// Generated by tools/gen/build_info.py. Do not edit.\n")
        handle.write(f'pub const version = "{match.group(1)}";\n')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
